import { chromium, devices } from '@playwright/test';
const b = await chromium.launch();
const ctx = await b.newContext({ ...devices['iPhone 14'] });
const p = await ctx.newPage();
const out = {};
await p.goto('https://earlysignal-nvs.vercel.app/', { waitUntil: 'networkidle' });
out.getStarted = await p.getByText('Get started').isVisible();
await p.getByRole('button', { name: 'I already have an account' }).click();
await p.getByLabel('Username').fill('maya_demo');
await p.getByLabel('Password').fill('Acorns2026!');
await p.getByRole('button', { name: 'Sign in', exact: true }).click();
await p.getByText(/^Hi, Maya$/).waitFor({ timeout: 20000 });
out.studentBurrow = true;
await p.screenshot({ path: 'docs/walkthrough/screens/live-student-burrow.png' });
await p.getByRole('tab', { name: 'Quests' }).click();
await p.getByText('Science lab write-up').first().waitFor();
out.questsVisible = true;
await p.getByRole('tab', { name: 'Me' }).click();
await p.getByText('Ana').first().waitFor();
out.parentLinkedShown = true;
await p.getByRole('button', { name: 'Sign out' }).click();
await p.getByText('Get started').waitFor();
await p.getByRole('button', { name: /I’m a parent/ }).click();
await p.getByLabel('Email').fill('earlysignal.demo.parent@gmail.com');
await p.getByLabel('Password').fill('Acorns2026!');
await p.getByRole('button', { name: 'Sign in', exact: true }).click();
await p.getByText(/Maya’s week/).waitFor({ timeout: 20000 });
out.parentSummary = true;
await p.screenshot({ path: 'docs/walkthrough/screens/live-parent-summary.png' });
console.log(JSON.stringify(out));
await b.close();
